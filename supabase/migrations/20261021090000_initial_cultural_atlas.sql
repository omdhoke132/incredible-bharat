-- Initial SQL schema for Incredible Bharat's cultural atlas.
-- Regional links are kept separate from record-specific citations: a state-level
-- source must not be presented as evidence for every cultural record in that state.

create table if not exists public.states (
  id text primary key,
  name text not null unique,
  region text,
  description text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.source_references (
  id bigint generated by default as identity primary key,
  title text not null,
  url text not null unique check (url ~* '^https?://'),
  publisher text,
  source_type text,
  license text,
  license_url text,
  accessed_at date,
  created_at timestamptz not null default now()
);

create table if not exists public.state_source_links (
  state_id text not null references public.states(id) on delete cascade,
  source_id bigint not null references public.source_references(id) on delete cascade,
  primary key (state_id, source_id)
);

create table if not exists public.cultural_records (
  record_key text primary key,
  state_id text not null references public.states(id) on delete cascade,
  category_key text not null check (
    category_key in (
      'heritage', 'traditions', 'festivals', 'arts', 'crafts', 'textiles',
      'music', 'instruments', 'cuisine', 'communities', 'culturalPlaces',
      'institutions', 'languages', 'literature', 'knowledgeHeritage'
    )
  ),
  legacy_id text not null,
  name text not null,
  region text,
  location text,
  city text,
  period text,
  era text,
  type text,
  category text,
  short_description text,
  description text not null,
  significance text,
  unesco_status text,
  icon text,
  image_url text,
  tags text[] not null default '{}',
  alternate_names text[] not null default '{}',
  description_status text not null default 'needs-curation',
  verification_status text not null default 'needs_review'
    check (verification_status in ('needs_review', 'partially_verified', 'verified', 'rejected')),
  raw_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (state_id, category_key, legacy_id)
);

create table if not exists public.cultural_record_source_links (
  record_key text not null references public.cultural_records(record_key) on delete cascade,
  source_id bigint not null references public.source_references(id) on delete cascade,
  citation_type text not null default 'supports',
  citation_note text,
  checked_at date,
  primary key (record_key, source_id)
);

create index if not exists cultural_records_state_category_idx
  on public.cultural_records (state_id, category_key);
create index if not exists cultural_records_name_idx
  on public.cultural_records (lower(name));
create index if not exists cultural_records_tags_idx
  on public.cultural_records using gin (tags);
create index if not exists cultural_records_search_idx
  on public.cultural_records using gin (
    to_tsvector(
      'simple',
      coalesce(name, '') || ' ' ||
      coalesce(description, '') || ' ' ||
      coalesce(significance, '') || ' ' ||
      coalesce(location, '') || ' ' ||
      coalesce(city, '')
    )
  );

-- Public visitors can read cultural material, but only trusted server-side
-- credentials may write. Never put a service-role/secret key in Vite code.
alter table public.states enable row level security;
alter table public.source_references enable row level security;
alter table public.state_source_links enable row level security;
alter table public.cultural_records enable row level security;
alter table public.cultural_record_source_links enable row level security;

revoke all on public.states from anon, authenticated;
revoke all on public.source_references from anon, authenticated;
revoke all on public.state_source_links from anon, authenticated;
revoke all on public.cultural_records from anon, authenticated;
revoke all on public.cultural_record_source_links from anon, authenticated;

grant select on public.states to anon, authenticated;
grant select on public.source_references to anon, authenticated;
grant select on public.state_source_links to anon, authenticated;
grant select on public.cultural_records to anon, authenticated;
grant select on public.cultural_record_source_links to anon, authenticated;

grant all on public.states to service_role;
grant all on public.source_references to service_role;
grant all on public.state_source_links to service_role;
grant all on public.cultural_records to service_role;
grant all on public.cultural_record_source_links to service_role;
grant usage, select on sequence public.source_references_id_seq to service_role;

create policy "Public can read states"
  on public.states for select to anon, authenticated using (true);
create policy "Public can read source references"
  on public.source_references for select to anon, authenticated using (true);
create policy "Public can read state source links"
  on public.state_source_links for select to anon, authenticated using (true);
create policy "Public can read cultural records"
  on public.cultural_records for select to anon, authenticated using (true);
create policy "Public can read record source links"
  on public.cultural_record_source_links for select to anon, authenticated using (true);
